// dynamic color was removed on purpose. with it on, the colors came from the
// phone's wallpaper, so the app looked different on every phone and mixed
// gold with lavender. now it's always the NMSU scheme from Color.kt
@Composable
fun CourseBadgeTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
        typography = Typography,
        content = content
    )
}

// both screens use this so the top bar is solid NMSU crimson with white text.
// in light mode the crimson is primary, in dark mode it's primaryContainer,
// that's why it checks the mode instead of always using the same role.
// MainActivity makes the status bar icons white to match
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun crimsonTopAppBarColors(): TopAppBarColors {
    val scheme = MaterialTheme.colorScheme
    val dark = isSystemInDarkTheme()
    val container = if (dark) scheme.primaryContainer else scheme.primary
    val content = if (dark) scheme.onPrimaryContainer else scheme.onPrimary
    return TopAppBarDefaults.topAppBarColors(
        containerColor = container,
        titleContentColor = content,
        navigationIconContentColor = content,
        actionIconContentColor = content
    )
}
